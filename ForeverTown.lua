local f = CreateFrame("Frame")
f:RegisterEvent("PLAYER_LOGIN")
f:SetScript("OnEvent", function()
	local T = _G.PintsTownData
	if not (T and T.npcs and T.strings and NS.MapToWorld) then return end
	local idx = {}
	for i, s in ipairs(T.strings) do idx[s] = i end
	for id, a in pairs(ADD) do
		if not T.npcs[id] then
			local sp = {}
			for k = 1, #a[6], 3 do
				local cont, wx, wy = NS.MapToWorld(a[6][k], a[6][k + 1], a[6][k + 2])
				if cont and wx then sp[#sp + 1] = cont; sp[#sp + 1] = wx; sp[#sp + 1] = wy end
			end
			if #sp > 0 then
				if not idx[a[2]] then T.strings[#T.strings + 1] = a[2]; idx[a[2]] = #T.strings end
				T.npcs[id] = { a[1], idx[a[2]], a[3], a[4], a[5], sp }
			end
		end
	end
end)
